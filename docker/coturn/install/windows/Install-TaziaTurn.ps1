#Requires -Version 5.1
<#
.SYNOPSIS
  One-click TAZIA helper TURN (coturn) for the local Wi‑Fi.

.DESCRIPTION
  Detects LAN IP, writes docker/coturn/.env, starts Docker Desktop if needed,
  opens Windows Firewall for TURN, brings coturn up, smoke-tests, prints the
  values to paste in TAZIA → Zones → Fix.

.PARAMETER Stop
  Stop the coturn container and exit.

.PARAMETER TestOnly
  Smoke-test an already running server (no recreate).

.PARAMETER Public
  Prefer public IP via api.ipify.org (peers outside your LAN / CGNAT).

.PARAMETER Pass
  Override TURN password (otherwise keep existing .env or generate one).

.PARAMETER FirewallOnly
  Only create the Windows Firewall inbound rule (run elevated once).

.EXAMPLE
  .\Install-TaziaTurn.ps1
  .\Install-TaziaTurn.ps1 -Stop
  .\Install-TaziaTurn.ps1 -TestOnly
  .\Install-TaziaTurn.ps1 -FirewallOnly
#>
[CmdletBinding()]
param(
  [switch]$Stop,
  [switch]$TestOnly,
  [switch]$Public,
  [switch]$FirewallOnly,
  [string]$Pass = ''
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$CoturnDir = (Resolve-Path (Join-Path $ScriptDir '..\..')).Path
$EnvFile = Join-Path $CoturnDir '.env'
$ComposeFile = Join-Path $CoturnDir 'docker-compose.yml'
$RuleName = 'TAZIA coturn TURN'
$DefaultUser = 'tazia'
$DefaultPort = 3478

function Write-Step([string]$Message) {
  Write-Host ""
  Write-Host "==> $Message" -ForegroundColor Cyan
}

function Write-Ok([string]$Message) {
  Write-Host "    OK  $Message" -ForegroundColor Green
}

function Write-WarnLine([string]$Message) {
  Write-Host "    !!  $Message" -ForegroundColor Yellow
}

function Get-LanIPv4 {
  $candidates = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
    Where-Object {
      $_.IPAddress -notlike '127.*' -and
      $_.IPAddress -notlike '169.254.*' -and
      $_.PrefixOrigin -ne 'WellKnown' -and
      $_.InterfaceAlias -notmatch 'vEthernet|WSL|Docker|Hyper-V|Loopback|Virtual|WSL|VPN|Tailscale|ZeroTier|Hamachi'
    } |
    Sort-Object -Property @{
      Expression = {
        if ($_.InterfaceAlias -match 'Wi-?Fi|Wireless|WLAN') { 0 }
        elseif ($_.InterfaceAlias -match 'Ethernet|LAN') { 1 }
        else { 2 }
      }
    }, PrefixLength

  if ($candidates) { return $candidates[0].IPAddress }

  # Fallback: first non-loopback IPv4 from ipconfig-style listing
  $fallback = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
    Where-Object { $_.IPAddress -notlike '127.*' -and $_.IPAddress -notlike '169.254.*' } |
    Select-Object -First 1
  if ($fallback) { return $fallback.IPAddress }
  throw 'No usable LAN IPv4 found. Connect to Wi‑Fi/Ethernet and retry.'
}

function Get-PublicIPv4 {
  try {
    $ip = (Invoke-RestMethod -Uri 'https://api.ipify.org' -TimeoutSec 8).Trim()
    if ($ip -match '^\d{1,3}(\.\d{1,3}){3}$') { return $ip }
  } catch { }
  throw 'Could not detect public IP. Pass EXTERNAL_IP manually or omit -Public.'
}

function New-TurnPassword {
  $bytes = New-Object byte[] 18
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  return [Convert]::ToBase64String($bytes).TrimEnd('=').Replace('+', 'x').Replace('/', 'y')
}

function Read-DotEnv([string]$Path) {
  $map = @{}
  if (-not (Test-Path $Path)) { return $map }
  Get-Content -LiteralPath $Path | ForEach-Object {
    $line = $_.Trim()
    if (-not $line -or $line.StartsWith('#')) { return }
    $idx = $line.IndexOf('=')
    if ($idx -lt 1) { return }
    $map[$line.Substring(0, $idx).Trim()] = $line.Substring($idx + 1).Trim()
  }
  return $map
}

function Write-DotEnv([string]$Path, [hashtable]$Map) {
  $lines = @(
    '# Generated by Install-TaziaTurn.ps1 — do not commit.',
    "TURN_USER=$($Map.TURN_USER)",
    "TURN_PASS=$($Map.TURN_PASS)",
    "TURN_PORT=$($Map.TURN_PORT)",
    "EXTERNAL_IP=$($Map.EXTERNAL_IP)",
    "DETECT_EXTERNAL_IP=$($Map.DETECT_EXTERNAL_IP)"
  )
  Set-Content -LiteralPath $Path -Value $lines -Encoding ascii
}

function Find-DockerDesktop {
  @(
    "$env:ProgramFiles\Docker\Docker\Docker Desktop.exe",
    "${env:ProgramFiles(x86)}\Docker\Docker\Docker Desktop.exe",
    "$env:LOCALAPPDATA\Programs\Docker\Docker\Docker Desktop.exe"
  ) | Where-Object { Test-Path $_ } | Select-Object -First 1
}

function Ensure-Docker {
  if (Get-Command docker -ErrorAction SilentlyContinue) {
    try {
      docker info 1>$null 2>$null
      if ($LASTEXITCODE -eq 0) { return }
    } catch { }
  }

  $exe = Find-DockerDesktop
  if (-not $exe) {
    throw @"
Docker Desktop is required (one-time install).
Download: https://www.docker.com/products/docker-desktop/
Then re-run this script.
"@
  }

  Write-Step 'Starting Docker Desktop…'
  Start-Process -FilePath $exe | Out-Null
  $deadline = (Get-Date).AddMinutes(3)
  while ((Get-Date) -lt $deadline) {
    Start-Sleep -Seconds 3
    try {
      docker info 1>$null 2>$null
      if ($LASTEXITCODE -eq 0) {
        Write-Ok 'Docker is ready'
        return
      }
    } catch { }
    Write-Host '    …waiting for Docker engine' -ForegroundColor DarkGray
  }
  throw 'Docker Desktop did not become ready in time. Open it manually and re-run.'
}

function Test-IsAdmin {
  $id = [Security.Principal.WindowsIdentity]::GetCurrent()
  $p = New-Object Security.Principal.WindowsPrincipal($id)
  return $p.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Set-TurnFirewall {
  Write-Step 'Windows Firewall (UDP 3478 + 49160-49200)'
  $existing = Get-NetFirewallRule -DisplayName $RuleName -ErrorAction SilentlyContinue
  if ($existing) {
    Write-Ok "Rule already present: $RuleName"
    return $true
  }
  if (-not (Test-IsAdmin)) {
    Write-WarnLine 'Firewall rule needs Administrator (once).'
    Write-Host "    Re-run elevated:  Start-Process powershell -Verb RunAs -ArgumentList '-NoProfile -ExecutionPolicy Bypass -File ""$PSCommandPath"" -FirewallOnly'" -ForegroundColor DarkGray
    try {
      Start-Process -FilePath powershell.exe -Verb RunAs -ArgumentList @(
        '-NoProfile', '-ExecutionPolicy', 'Bypass',
        '-File', $PSCommandPath, '-FirewallOnly'
      ) -Wait | Out-Null
      $existing = Get-NetFirewallRule -DisplayName $RuleName -ErrorAction SilentlyContinue
      if ($existing) {
        Write-Ok "Created inbound rule: $RuleName"
        return $true
      }
    } catch {
      Write-WarnLine 'UAC elevation cancelled or failed.'
    }
    Write-WarnLine 'Peers on other devices may be blocked until the rule exists.'
    return $false
  }
  try {
    New-NetFirewallRule -DisplayName $RuleName -Direction Inbound -Action Allow `
      -Protocol UDP -LocalPort 3478,49160-49200 -Profile Private,Domain `
      -ErrorAction Stop | Out-Null
    Write-Ok "Created inbound rule: $RuleName"
    return $true
  } catch {
    Write-WarnLine "Could not create firewall rule: $($_.Exception.Message)"
    return $false
  }
}

function Invoke-TurnSmoke([string]$User, [string]$Password, [string]$ExternalIp) {
  Write-Step 'Smoke test (STUN + TURN allocate)'
  $stun = docker compose -f $ComposeFile exec -T coturn turnutils_stunclient 127.0.0.1 2>&1 | Out-String
  if ($LASTEXITCODE -ne 0) { throw "STUN smoke failed:`n$stun" }
  Write-Ok 'STUN binding ok'

  $turn = docker compose -f $ComposeFile exec -T coturn `
    turnutils_uclient -v -t -u $User -w $Password -e 1.1.1.1 127.0.0.1 2>&1 | Out-String
  if ($LASTEXITCODE -ne 0) { throw "TURN smoke failed:`n$turn" }
  if ($turn -notmatch 'Received relay addr') {
    throw "TURN allocate did not return a relay addr:`n$turn"
  }
  if ($turn -match "Received relay addr:\s*$([regex]::Escape($ExternalIp)):\d+") {
    Write-Ok "TURN relay on $ExternalIp"
  } else {
    Write-WarnLine 'Relay address did not match EXTERNAL_IP — check .env EXTERNAL_IP vs LAN IP'
    Write-Host $turn
  }
  if ($turn -match 'channel bind.*success|success') {
    Write-Ok 'Channel bind ok'
  }
}

function Show-TaziaCard([hashtable]$Map) {
  $url = "turn:$($Map.EXTERNAL_IP):$($Map.TURN_PORT)"
  $card = @"

┌──────────────────────────────────────────────┐
│  TAZIA → Zonas → Arreglar / Zones → Fix      │
├──────────────────────────────────────────────┤
│  Usar servidor de apoyo / Helper:  ON        │
│  URL:         $url
│  Usuario:     $($Map.TURN_USER)
│  Contraseña:  $($Map.TURN_PASS)
│  Ocultar IP:  ON (por defecto)               │
└──────────────────────────────────────────────┘
  Ambos peers: misma config → salir y volver a entrar en la zona.
  Misma Wi‑Fi + P2P directo: desmarca «Ocultar mi dirección…».
"@
  Write-Host $card -ForegroundColor White
  try {
    Set-Clipboard -Value @"
$url
$($Map.TURN_USER)
$($Map.TURN_PASS)
"@
    Write-Ok 'URL / user / pass copied to clipboard (3 lines)'
  } catch {
    Write-WarnLine 'Clipboard unavailable — copy from the card above.'
  }
}

# --- main ---
if (-not (Test-Path $ComposeFile)) {
  throw "docker-compose.yml not found at $ComposeFile"
}

if ($FirewallOnly) {
  if (-not (Set-TurnFirewall)) { exit 1 }
  exit 0
}

Ensure-Docker

Push-Location $CoturnDir
try {
  if ($Stop) {
    Write-Step 'Stopping TAZIA coturn'
    docker compose -f $ComposeFile down
    Write-Ok 'Stopped'
    return
  }

  $existing = Read-DotEnv $EnvFile
  $user = if ($existing.TURN_USER) { $existing.TURN_USER } else { $DefaultUser }
  $port = if ($existing.TURN_PORT) { $existing.TURN_PORT } else { "$DefaultPort" }
  $password = if ($Pass) {
    $Pass
  } elseif ($existing.TURN_PASS -and $existing.TURN_PASS -notmatch 'change-me') {
    $existing.TURN_PASS
  } else {
    New-TurnPassword
  }

  if ($TestOnly) {
    if (-not $existing.EXTERNAL_IP -or -not $existing.TURN_PASS) {
      throw 'No .env yet. Run without -TestOnly first.'
    }
    docker compose -f $ComposeFile ps
    Invoke-TurnSmoke -User $existing.TURN_USER -Password $existing.TURN_PASS -ExternalIp $existing.EXTERNAL_IP
    Show-TaziaCard $existing
    return
  }

  Write-Step 'Detecting host address'
  $externalIp = if ($Public) { Get-PublicIPv4 } else { Get-LanIPv4 }
  Write-Ok "EXTERNAL_IP=$externalIp$(if ($Public) { ' (public)' } else { ' (LAN)' })"

  $map = @{
    TURN_USER          = $user
    TURN_PASS          = $password
    TURN_PORT          = $port
    EXTERNAL_IP        = $externalIp
    DETECT_EXTERNAL_IP = '0'
  }
  Write-DotEnv -Path $EnvFile -Map $map
  Write-Ok "Wrote $EnvFile"

  Set-TurnFirewall

  Write-Step 'Starting coturn'
  docker compose -f $ComposeFile up -d --force-recreate
  if ($LASTEXITCODE -ne 0) { throw 'docker compose up failed' }

  $healthyDeadline = (Get-Date).AddMinutes(2)
  do {
    Start-Sleep -Seconds 3
    $ps = docker compose -f $ComposeFile ps --format json 2>$null | Out-String
    if ($ps -match '"Health"\s*:\s*"healthy"' -or $ps -match 'healthy') { break }
    $status = docker compose -f $ComposeFile ps 2>&1 | Out-String
    if ($status -match 'healthy') { break }
  } while ((Get-Date) -lt $healthyDeadline)

  docker compose -f $ComposeFile ps
  Invoke-TurnSmoke -User $map.TURN_USER -Password $map.TURN_PASS -ExternalIp $map.EXTERNAL_IP
  Show-TaziaCard $map
  Write-Host ""
  Write-Host "Stop later:  .\Install-TaziaTurn.ps1 -Stop" -ForegroundColor DarkGray
  Write-Host "Retest:      .\Install-TaziaTurn.ps1 -TestOnly" -ForegroundColor DarkGray
}
finally {
  Pop-Location
}
