#!/usr/bin/env bash
# One-click TAZIA helper TURN (coturn) for macOS / Linux LAN.
# Usage:
#   ./install-tazia-turn.sh           # start (LAN IP)
#   ./install-tazia-turn.sh --public  # prefer public IP
#   ./install-tazia-turn.sh --stop
#   ./install-tazia-turn.sh --test
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
COTURN_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
ENV_FILE="$COTURN_DIR/.env"
COMPOSE_FILE="$COTURN_DIR/docker-compose.yml"
DEFAULT_USER=tazia
DEFAULT_PORT=3478

MODE=start
USE_PUBLIC=0
PASS_OVERRIDE=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --stop) MODE=stop; shift ;;
    --test) MODE=test; shift ;;
    --public) USE_PUBLIC=1; shift ;;
    --pass) PASS_OVERRIDE="${2:-}"; shift 2 ;;
    -h|--help)
      sed -n '1,12p' "$0"
      exit 0
      ;;
    *) echo "Unknown option: $1" >&2; exit 1 ;;
  esac
done

step() { printf '\n==> %s\n' "$*"; }
ok() { printf '    OK  %s\n' "$*"; }
warn() { printf '    !!  %s\n' "$*"; }

need_docker() {
  if ! command -v docker >/dev/null 2>&1; then
    cat >&2 <<'EOF'
Docker is required (one-time).

  macOS:  https://www.docker.com/products/docker-desktop/
          or: brew install --cask docker
  Linux:  https://docs.docker.com/engine/install/

Then re-run this script.
EOF
    exit 1
  fi
  if ! docker info >/dev/null 2>&1; then
    step "Starting Docker…"
    if [[ "$(uname -s)" == "Darwin" ]]; then
      open -a Docker 2>/dev/null || true
    elif command -v systemctl >/dev/null 2>&1; then
      sudo systemctl start docker 2>/dev/null || true
    fi
    deadline=$((SECONDS + 180))
    while (( SECONDS < deadline )); do
      if docker info >/dev/null 2>&1; then
        ok "Docker is ready"
        return
      fi
      sleep 3
      printf '    …waiting for Docker engine\n'
    done
    echo "Docker did not become ready. Open Docker Desktop / start the daemon and retry." >&2
    exit 1
  fi
}

lan_ip() {
  local ip=""
  if [[ "$(uname -s)" == "Darwin" ]]; then
    for iface in en0 en1 en2; do
      ip="$(ipconfig getifaddr "$iface" 2>/dev/null || true)"
      [[ -n "$ip" ]] && { echo "$ip"; return; }
    done
  fi
  if command -v ip >/dev/null 2>&1; then
    ip="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}' || true)"
    [[ -n "$ip" ]] && { echo "$ip"; return; }
  fi
  ip="$(hostname -I 2>/dev/null | awk '{print $1}' || true)"
  [[ -n "$ip" ]] && { echo "$ip"; return; }
  echo "No usable LAN IPv4 found." >&2
  exit 1
}

public_ip() {
  local ip
  ip="$(curl -fsS --max-time 8 https://api.ipify.org || true)"
  if [[ "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "$ip"
    return
  fi
  echo "Could not detect public IP." >&2
  exit 1
}

gen_pass() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 18 | tr -d '=+/' | tr '+/' 'xy' | head -c 24
    echo
  else
    head -c 24 /dev/urandom | base64 | tr -d '=+/' | head -c 24
    echo
  fi
}

read_env_val() {
  local key="$1"
  [[ -f "$ENV_FILE" ]] || return 0
  grep -E "^${key}=" "$ENV_FILE" | head -n1 | cut -d= -f2-
}

write_env() {
  local user="$1" pass="$2" port="$3" ext="$4"
  cat >"$ENV_FILE" <<EOF
# Generated by install-tazia-turn.sh — do not commit.
TURN_USER=$user
TURN_PASS=$pass
TURN_PORT=$port
EXTERNAL_IP=$ext
DETECT_EXTERNAL_IP=0
EOF
}

open_firewall_hint() {
  step "Firewall"
  case "$(uname -s)" in
    Darwin)
      ok "macOS usually allows Docker published ports on the LAN"
      warn "If peers fail: System Settings → Network → Firewall → allow Docker"
      ;;
    Linux)
      if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -qi active; then
        sudo ufw allow 3478/udp comment 'TAZIA TURN' || true
        sudo ufw allow 3478/tcp comment 'TAZIA TURN' || true
        sudo ufw allow 49160:49200/udp comment 'TAZIA TURN relay' || true
        ok "Opened UFW for TURN + relay range"
      else
        warn "Ensure UDP 3478 and 49160-49200 are reachable on this host"
      fi
      ;;
  esac
}

smoke() {
  local user="$1" pass="$2" ext="$3"
  step "Smoke test (STUN + TURN allocate)"
  docker compose -f "$COMPOSE_FILE" exec -T coturn turnutils_stunclient 127.0.0.1 >/dev/null
  ok "STUN binding ok"
  local out
  out="$(docker compose -f "$COMPOSE_FILE" exec -T coturn \
    turnutils_uclient -v -t -u "$user" -w "$pass" -e 1.1.1.1 127.0.0.1 2>&1 || true)"
  if ! grep -q "Received relay addr" <<<"$out"; then
    printf '%s\n' "$out" >&2
    echo "TURN allocate failed" >&2
    exit 1
  fi
  if grep -q "Received relay addr: ${ext}:" <<<"$out"; then
    ok "TURN relay on $ext"
  else
    warn "Relay address did not match EXTERNAL_IP — check .env"
    printf '%s\n' "$out"
  fi
  ok "Channel bind path exercised"
}

show_card() {
  local user="$1" pass="$2" port="$3" ext="$4"
  local url="turn:${ext}:${port}"
  cat <<EOF

┌──────────────────────────────────────────────┐
│  TAZIA → Zones → Fix / Zonas → Arreglar      │
├──────────────────────────────────────────────┤
│  Helper server: ON                           │
│  URL:         $url
│  Username:    $user
│  Password:    $pass
│  Hide IP:     ON (default)                   │
└──────────────────────────────────────────────┘
  Both peers: same config → leave and rejoin the zone.
  Same Wi‑Fi P2P: uncheck “Hide my internet address”.

EOF
  if command -v pbcopy >/dev/null 2>&1; then
    printf '%s\n%s\n%s\n' "$url" "$user" "$pass" | pbcopy
    ok "URL / user / pass copied to clipboard (3 lines)"
  elif command -v xclip >/dev/null 2>&1; then
    printf '%s\n%s\n%s\n' "$url" "$user" "$pass" | xclip -selection clipboard
    ok "URL / user / pass copied to clipboard (3 lines)"
  fi
}

[[ -f "$COMPOSE_FILE" ]] || { echo "Missing $COMPOSE_FILE" >&2; exit 1; }
need_docker
cd "$COTURN_DIR"

if [[ "$MODE" == "stop" ]]; then
  step "Stopping TAZIA coturn"
  docker compose -f "$COMPOSE_FILE" down
  ok "Stopped"
  exit 0
fi

USER_NAME="$(read_env_val TURN_USER)"; USER_NAME="${USER_NAME:-$DEFAULT_USER}"
PORT="$(read_env_val TURN_PORT)"; PORT="${PORT:-$DEFAULT_PORT}"
EXISTING_PASS="$(read_env_val TURN_PASS)"
EXISTING_IP="$(read_env_val EXTERNAL_IP)"

if [[ "$MODE" == "test" ]]; then
  [[ -n "$EXISTING_PASS" && -n "$EXISTING_IP" ]] || { echo "No .env yet — run without --test first." >&2; exit 1; }
  docker compose -f "$COMPOSE_FILE" ps
  smoke "$USER_NAME" "$EXISTING_PASS" "$EXISTING_IP"
  show_card "$USER_NAME" "$EXISTING_PASS" "$PORT" "$EXISTING_IP"
  exit 0
fi

step "Detecting host address"
if [[ "$USE_PUBLIC" -eq 1 ]]; then
  EXT_IP="$(public_ip)"
  ok "EXTERNAL_IP=$EXT_IP (public)"
else
  EXT_IP="$(lan_ip)"
  ok "EXTERNAL_IP=$EXT_IP (LAN)"
fi

if [[ -n "$PASS_OVERRIDE" ]]; then
  PASS="$PASS_OVERRIDE"
elif [[ -n "$EXISTING_PASS" && "$EXISTING_PASS" != *change-me* ]]; then
  PASS="$EXISTING_PASS"
else
  PASS="$(gen_pass)"
fi

write_env "$USER_NAME" "$PASS" "$PORT" "$EXT_IP"
ok "Wrote $ENV_FILE"
open_firewall_hint

step "Starting coturn"
docker compose -f "$COMPOSE_FILE" up -d --force-recreate

deadline=$((SECONDS + 120))
while (( SECONDS < deadline )); do
  if docker compose -f "$COMPOSE_FILE" ps 2>/dev/null | grep -qi healthy; then
    break
  fi
  sleep 3
done
docker compose -f "$COMPOSE_FILE" ps
smoke "$USER_NAME" "$PASS" "$EXT_IP"
show_card "$USER_NAME" "$PASS" "$PORT" "$EXT_IP"

printf 'Stop later:  %s --stop\n' "$0"
printf 'Retest:      %s --test\n' "$0"
